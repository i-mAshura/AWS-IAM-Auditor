"""Auto-Remediation Engine guarded by a mandatory dry-run flag by default."""
from typing import List, Dict, Any, Optional
from .models import Finding, LeastPrivilegeSuggestion, RemediationAction


class IAMAutoRemediator:
    """Safely disables stale access keys and prepares/applies least-privilege policy replacements."""

    def __init__(self, dry_run: bool = True, boto3_session: Optional[Any] = None):
        self.dry_run = dry_run
        self.boto3_session = boto3_session
        if not self.dry_run and self.boto3_session is None:
            try:
                import boto3
                self.boto3_session = boto3.Session()
            except Exception:
                self.boto3_session = None
        self.actions_log: List[RemediationAction] = []

    def remediate_stale_keys(self, findings: List[Finding]) -> List[RemediationAction]:
        """Disables stale or never-used IAM access keys identified by the scanner."""
        key_findings = [f for f in findings if f.category == "UNUSED_ACCESS_KEY"]
        new_actions: List[RemediationAction] = []
        for f in key_findings:
            access_key_id = f.evidence.get("AccessKeyId", "UNKNOWN_KEY")
            user_name = f.principal_name

            if self.dry_run:
                action = RemediationAction(
                    action_type="DISABLE_ACCESS_KEY",
                    principal_name=user_name,
                    target_id=access_key_id,
                    dry_run=True,
                    executed=False,
                    status="DRY_RUN_PLANNED",
                    details={
                        "api_call": "iam.update_access_key",
                        "parameters": {
                            "UserName": user_name,
                            "AccessKeyId": access_key_id,
                            "Status": "Inactive",
                        },
                        "reason": f.title,
                    },
                )
            else:
                executed = False
                status = "EXECUTED_KEY_DISABLED"
                err_msg = None
                if self.boto3_session is not None:
                    try:
                        iam = self.boto3_session.client("iam")
                        iam.update_access_key(UserName=user_name, AccessKeyId=access_key_id, Status="Inactive")
                        executed = True
                    except Exception as exc:
                        status = "FAILED_EXECUTION"
                        err_msg = str(exc)
                else:
                    status = "SKIPPED_NO_SESSION"

                details = {
                    "api_call": "iam.update_access_key",
                    "parameters": {
                        "UserName": user_name,
                        "AccessKeyId": access_key_id,
                        "Status": "Inactive",
                    },
                    "reason": f.title,
                }
                if err_msg:
                    details["error"] = err_msg

                action = RemediationAction(
                    action_type="DISABLE_ACCESS_KEY",
                    principal_name=user_name,
                    target_id=access_key_id,
                    dry_run=False,
                    executed=executed,
                    status=status,
                    details=details,
                )
            new_actions.append(action)
            self.actions_log.append(action)
        return new_actions

    def remediate_policies(self, suggestions: List[LeastPrivilegeSuggestion]) -> List[RemediationAction]:
        """Generates or applies least-privilege policy replacements for over-privileged roles."""
        new_actions: List[RemediationAction] = []
        for s in suggestions:
            policy_name = f"{s.role_name}-LeastPrivilegeAutoGenerated"
            if self.dry_run:
                action = RemediationAction(
                    action_type="REPLACE_ROLE_POLICY",
                    principal_name=s.role_name,
                    target_id=policy_name,
                    dry_run=True,
                    executed=False,
                    status="DRY_RUN_POLICY_SUGGESTED",
                    details={
                        "api_call": "iam.put_role_policy",
                        "parameters": {
                            "RoleName": s.role_name,
                            "PolicyName": policy_name,
                            "PolicyDocument": s.generated_policy,
                        },
                        "wildcard_actions_removed": s.current_wildcard_actions,
                        "observed_cloudtrail_events": s.observed_event_count,
                    },
                )
            else:
                executed = False
                status = "EXECUTED_POLICY_APPLIED"
                err_msg = None
                if self.boto3_session is not None:
                    try:
                        import json
                        iam = self.boto3_session.client("iam")
                        iam.put_role_policy(
                            RoleName=s.role_name,
                            PolicyName=policy_name,
                            PolicyDocument=json.dumps(s.generated_policy),
                        )
                        executed = True
                    except Exception as exc:
                        status = "FAILED_EXECUTION"
                        err_msg = str(exc)
                else:
                    status = "SKIPPED_NO_SESSION"

                details = {
                    "api_call": "iam.put_role_policy",
                    "parameters": {
                        "RoleName": s.role_name,
                        "PolicyName": policy_name,
                        "PolicyDocument": s.generated_policy,
                    },
                }
                if err_msg:
                    details["error"] = err_msg

                action = RemediationAction(
                    action_type="REPLACE_ROLE_POLICY",
                    principal_name=s.role_name,
                    target_id=policy_name,
                    dry_run=False,
                    executed=executed,
                    status=status,
                    details=details,
                )
            new_actions.append(action)
            self.actions_log.append(action)
        return new_actions
